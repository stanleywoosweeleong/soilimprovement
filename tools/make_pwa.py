"""Write manifest.webmanifest and sw.js next to index.html. The service worker's
cache version is a hash of the shipped files, so every change triggers an update."""
import hashlib, json, os, sys
root = sys.argv[1] if len(sys.argv) > 1 else "."
FILES = ["index.html", "manifest.webmanifest", "icons/icon-192.png", "icons/icon-512.png",
         "icons/icon-maskable-512.png", "icons/apple-touch-icon.png", "icons/favicon-32.png", "icons/favicon.ico"]
manifest = {
    "id": "./", "name": "Huang Soil Atlas", "short_name": "Soil Atlas",
    "description": "Dr. Huang Jui-chang's soil research and soil recovery methods, in English, Simplified Chinese, Traditional Chinese and Malay. Works offline.",
    "lang": "en", "dir": "ltr", "start_url": "./", "scope": "./", "display": "standalone",
    "background_color": "#F2F4EE", "theme_color": "#1E2B21", "categories": ["education", "productivity"],
    "icons": [
        {"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
        {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
        {"src": "icons/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"}]}
open(os.path.join(root, "manifest.webmanifest"), "w", encoding="utf-8").write(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
import subprocess
missing = [f for f in FILES if not os.path.exists(os.path.join(root, f))]
if missing:
    sys.exit("make_pwa: missing files to precache: %s (run tools/make_icons.py?)" % missing)
try:
    tracked = set(subprocess.run(["git", "ls-files"], cwd=root, capture_output=True, text=True).stdout.split())
    untracked = [f for f in FILES if f not in tracked and f != "index.html" and f != "manifest.webmanifest"]
    if tracked and untracked:
        print("WARNING: not tracked by git, so they will 404 on GitHub Pages and break install:", untracked)
except FileNotFoundError:
    pass
h = hashlib.sha256()
for f in FILES:
    h.update(open(os.path.join(root, f), "rb").read())
version = h.hexdigest()[:12]
sw = r"""/* Huang Soil Atlas service worker. Generated by tools/make_pwa.py; do not edit by hand. */
const VERSION = '%s';
const CACHE = 'soil-atlas-' + VERSION;
const FONT_CACHE = 'soil-atlas-fonts-v2';
const PRECACHE = %s;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await cache.addAll(PRECACHE.map((u) => new Request(u, { cache: 'reload' })));
    if (!self.registration.active) await self.skipWaiting(); // first install: take over at once
  })());
});

self.addEventListener('message', (event) => {
  if (event.data === 'skipWaiting') self.skipWaiting();
  if (event.data && event.data.type === 'cacheFonts') {
    event.waitUntil((async () => {
      const cache = await caches.open(FONT_CACHE);
      for (const u of event.data.urls.slice(0, 200)) {
        if (!/^https:\/\/fonts\.(googleapis|gstatic)\.com\//.test(u) || await cache.match(u)) continue;
        try {
          const res = await fontFetch(u);
          if (res.ok) await cache.put(u, res);
        } catch (e) { /* offline or blocked: try again next visit */ }
      }
    })());
  }
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k.startsWith('soil-atlas-') && k !== CACHE && k !== FONT_CACHE).map((k) => caches.delete(k)));
    await self.clients.claim();
  })());
});

// Google Fonts serves CORS headers, so fetch in cors mode and keep only real successes
// (an opaque no-cors response could hide an error page and would be cached for good).
async function fontFetch(url) {
  return fetch(new Request(url, { mode: 'cors', credentials: 'omit' }));
}
async function fontFromCache(request) {
  const cache = await caches.open(FONT_CACHE);
  const hit = await cache.match(request.url);
  if (hit) return hit;
  const res = await fontFetch(request.url);
  if (res.ok) cache.put(request.url, res.clone());
  return res;
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    event.respondWith(fontFromCache(req).catch(() => new Response('', { status: 504 })));
    return;
  }
  if (url.origin !== self.location.origin || !url.pathname.startsWith(new URL(self.registration.scope).pathname)) return;
  if (req.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      return (await cache.match('./index.html')) || fetch(req);
    })());
    return;
  }
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    return (await cache.match(req, { ignoreSearch: true })) || fetch(req);
  })());
});
""" % (version, json.dumps(["./" + f for f in FILES]))
open(os.path.join(root, "sw.js"), "w", encoding="utf-8").write(sw)
print("manifest + sw.js written, version", version)
